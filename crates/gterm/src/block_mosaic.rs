//! Мозаики (ADR-0022): секстанты 2×3, октанты 2×4, блоки «Centered» и восьмушки — заливка клеток
//! ровной сетки ячейки, как квадранты и восьмушки [`crate::box_drawing`]. Границы клеток считаются
//! одной формулой для всех наборов, поэтому октанты ложатся на квадранты, а соседние ячейки
//! смыкаются без зазоров и наложений.

use crate::procedural::{Canvas, in_ranges};

/// Диапазоны мозаик (включительно): октанты и половины четвертей (Unicode 16), секстанты,
/// восьмушки, «Centered».
pub const RANGES: &[(char, char)] = &[
	('\u{25A0}', '\u{25A0}'),
	('\u{1CD00}', '\u{1CDE5}'),
	('\u{1CEA0}', '\u{1CEA0}'),
	('\u{1CEA3}', '\u{1CEA3}'),
	('\u{1CEA8}', '\u{1CEA8}'),
	('\u{1CEAB}', '\u{1CEAB}'),
	('\u{1FB00}', '\u{1FB3B}'),
	('\u{1FB82}', '\u{1FB8B}'),
	('\u{1FBE4}', '\u{1FBE7}'),
];

