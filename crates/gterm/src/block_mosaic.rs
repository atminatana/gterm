/// Восьмушки U+1FB82–U+1FB86 (верхние) и U+1FB87–U+1FB8B (правые): число восьмых — 2, 3, 5, 6, 7;
/// 4/8 — это ▀ и ▐ из основного блока.
const EIGHTHS: [i32; 5] = [2, 3, 5, 6, 7];

/// Входит ли кодовая точка в мозаики.
pub fn is_mosaic(ch: char) -> bool {
	in_ranges(ch, RANGES)
}

/// Нарисовать мозаику в буфер покрытия `w × h` (row-major). `false` — не мозаика или негодный
/// буфер, буфер не тронут.
pub fn draw(ch: char, w: usize, h: usize, out: &mut [u8]) -> bool {
	if !is_mosaic(ch) {
		return false;
	}
	let Some(mut c) = Canvas::cleared(w, h, out) else {
		return false;
	};
	let cp = u32::from(ch);
	match cp {
		0x1FB00..=0x1FB3B => fill_grid(&mut c, 2, 3, SEXTANTS[(cp - 0x1FB00) as usize].into()),
		0x1CD00..=0x1CDE5 => fill_grid(&mut c, 2, 4, OCTANTS[(cp - 0x1CD00) as usize].into()),
		// Половины четвертей (Unicode 16) и средние четверти — клетки той же сетки 2×4.
		0x1CEA8 => fill_grid(&mut c, 2, 4, 0b0000_0001), // верх-лево
		0x1CEAB => fill_grid(&mut c, 2, 4, 0b0000_0010), // верх-право
		0x1CEA3 => fill_grid(&mut c, 2, 4, 0b0100_0000), // низ-лево
		0x1CEA0 => fill_grid(&mut c, 2, 4, 0b1000_0000), // низ-право
		0x1FBE6 => fill_grid(&mut c, 2, 4, 0b0001_0100), // середина слева
		0x1FBE7 => fill_grid(&mut c, 2, 4, 0b0010_1000), // середина справа
		// «Centered» — сетка 4×4: центральный блок и четверти, прижатые к середине стороны.
		0x25A0 => fill_grid(&mut c, 4, 4, 0x0660),
		0x1FBE4 => fill_grid(&mut c, 4, 4, 0x0066),
		0x1FBE5 => fill_grid(&mut c, 4, 4, 0x6600),
		0x1FB82..=0x1FB86 => {
			let n = EIGHTHS[(cp - 0x1FB82) as usize];
			c.rect(0, 0, w as i32, edge(h, n, 8), 255);
		}
		0x1FB87..=0x1FB8B => {
			let n = EIGHTHS[(cp - 0x1FB87) as usize];
			c.rect(edge(w, 8 - n, 8), 0, w as i32, h as i32, 255);
		}
		_ => return false,
	}
	true
}

/// Граница клетки `k` из `n` по длине `len` — округление к ближайшему: та же формула, что у
/// восьмушек и квадрантов, поэтому сетки всех наборов совпадают.
fn edge(len: usize, k: i32, n: i32) -> i32 {
	(len as i32 * k + n / 2) / n
}

/// Залить клетки сетки `cols × rows` по маске: бит `row · cols + col`, младший — верх-лево.
fn fill_grid(c: &mut Canvas, cols: i32, rows: i32, mask: u32) {
	for row in 0..rows {
		for col in 0..cols {
			if mask & (1 << (row * cols + col)) != 0 {
				c.rect(
					edge(c.w, col, cols),
					edge(c.h, row, rows),
					edge(c.w, col + 1, cols),
					edge(c.h, row + 1, rows),
					255,
				);
			}
		}
	}
}
